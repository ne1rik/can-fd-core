#!/usr/bin/env python3
"""Generate docs/VERIFICATION.md and .ru.md from recorded logs.

Metrics come from make_report.metrics(); the mutant table is parsed from
logs/mutation_model.log. Nothing is written by hand.
"""
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from make_report import metrics, LOGS  # noqa: E402

OUT = ROOT / "docs"


def mutants():
    rows = []
    txt = (LOGS / "mutation_model.log").read_text(errors="replace")
    pat = r"^(\w+)\s+(KILLED|SURVIVED|UNEXPECTED-\w+|SKIP|ERROR)\s+(\w+)\s+(.+)$"
    for line in txt.splitlines():
        m = re.match(pat, line.strip())
        if m:
            rows.append(m.groups())
    return rows


def gate_table(m, lang):
    if lang == "en":
        hdr = "| Gate | Result | Evidence |\n|---|---|---|\n"
        rows = [
            ("CTU vectors through RTL", f'{m["ctu_passed"]} / {m["ctu_total"]}, 0 failures', "logs/ctu_*.log"),
            ("Model-vs-RTL sweep", f'{m["sweep_cases"]} cases, {m["sweep_fails"]} failures', "logs/big_*.log"),
            ("CRC-boundary stuffing", f'{m["bnd_cases"]} cases, {m["bnd_fails"]} failures', "logs/bnd_*.log"),
            ("Model unit tests", f'{m["pytest"]} passed', "logs/regress.log"),
            ("Model vs CTU waveforms", f'{m["xval_matched"]} matched, {m["xval_mismatch"]} mismatch, {m["xval_deferred"]} deferred', "logs/xval_model.log"),
            ("Mutation testing", f'{m["mut_killed"]}/{m["mut_total"]} killed, {m["mut_gaps"]} gaps, {m["mut_problems"]} problems', "logs/mutation_model.log"),
        ]
    else:
        hdr = "| Гейт | Результат | Доказательство |\n|---|---|---|\n"
        rows = [
            ("CTU-векторы через RTL", f'{m["ctu_passed"]} / {m["ctu_total"]}, 0 отказов', "logs/ctu_*.log"),
            ("Прогон модель-против-RTL", f'{m["sweep_cases"]} кейсов, {m["sweep_fails"]} отказов', "logs/big_*.log"),
            ("Стаффинг на границе CRC", f'{m["bnd_cases"]} кейсов, {m["bnd_fails"]} отказов', "logs/bnd_*.log"),
            ("Юнит-тесты модели", f'{m["pytest"]} пройдено', "logs/regress.log"),
            ("Модель против осциллограмм CTU", f'{m["xval_matched"]} совпало, {m["xval_mismatch"]} расхождений, {m["xval_deferred"]} отложено', "logs/xval_model.log"),
            ("Мутационное тестирование", f'{m["mut_killed"]}/{m["mut_total"]} убито, {m["mut_gaps"]} пробелов, {m["mut_problems"]} проблем', "logs/mutation_model.log"),
        ]
    return hdr + "".join(f"| {a} | {b} | `{c}` |\n" for a, b, c in rows)


def build(m, lang):
    mut = mutants()
    c = m["corpus"]
    corpus_lines = "".join(f"| `{k}` | {v} |\n" for k, v in c["by_format"].items())
    mut_lines = "".join(f"| `{n}` | {res} | {desc} |\n" for n, res, exp, desc in mut)

    if lang == "en":
        return f"""# Verification methodology and evidence

Generated by `scripts/make_docs.py` from `logs/` and `coverage/`.
Revision: `{m["git"]}` · Date: {date.today().isoformat()}

Every number below is parsed from a recorded run. If a log is missing the
value shows as `n/a` rather than a plausible substitute.

## 1. What is measured

{gate_table(m, lang)}
## 2. Corpus composition

| Format | Vectors |
|---|---|
{corpus_lines}| **Total** | **{c["total"]}** |
| of which synthetic | {c["synthetic"]} |

Vectors are extracted from the open CTU CAN FD reference dataset
(`reference_data_set_*.vhd` under `test/main_tb/`). These are reference
simulation datasets, not silicon captures. Synthetic frames are marked
`synthetic: true` and exist to close a CRC-21 mutation gap; they are used by
the model mutation harness, not by the RTL corpus run. That is why the corpus
total and the RTL run total differ.

## 3. Comparison rules

* **ACK slot is excluded.** The receiver drives it dominant; the transmitter
  model outputs recessive. A difference at that single position is expected
  and is not counted as a mismatch.
* **Prefix must match exactly.** All bits up to and including the CRC
  delimiter are compared bit-by-bit.
* **Tail must be recessive.** ACK delimiter, EOF and idle padding.
* **Out of scope:** remote frames (`rtr=1`), injected errors (`erf=1`),
  error-state frames (`esi=1`).

## 4. Mutation testing

Faults are injected into the reference model. A mutant must be detected by
the comparison harness; a survivor means the corpus does not constrain that
behaviour.

| Mutant | Result | Injected fault |
|---|---|---|
{mut_lines}
## 5. Real two-phase timing

`can_bit_timing` produces `sample_en` at tick `TSEG1` and `bit_boundary` at
the last tick of `SYNC(1) + TSEG1 + TSEG2`. A `brs_active` edge realigns
`clk_cnt` and `tseg_cnt`, so the new phase always starts a fresh bit.

The receiver switches phase in two stages: the BRS value is latched at its
sample point, then the phase is committed on the bit boundary that ends the
nominal BRS bit — the same event the transmitter uses. Reading the latch in
the sample cycle does not work: it is written by a non-blocking assignment in
that same cycle.

Covered by `tests/test_bit_timing.py`, `tests/test_timing_phase_switch.py`
and `tests/test_timing_matrix.py` (DLC 0/4/8/12/15 × BRS on/off × payload
patterns 0x00 / 0xFF / alternating, for both FBFF and FEFF).

## 6. Boundaries of what is proven

* **{m["xval_deferred"]} FD BRS=1 vectors are deferred** in the waveform
  cross-check: it samples at a fixed rate and cannot follow a mid-frame rate
  switch. Those frames are covered by the real-timing matrix instead.
* **Prescaler > 1 with a very short data phase** (`NBT_PRESCALER=2`, DBT=3
  clocks) fails the matrix. Reproduced on the pre-fix baseline, so it is a
  pre-existing resynchronisation limitation, not a regression.
* **Fault confinement is not implemented.** TEC/REC, error frames, bus-off.
* **Simulation only.** No FPGA build, no silicon, no ISO 26262 qualification.

## 7. Environment hazards found

* **Stale build reuse.** The build directory encodes timing parameters.
  Running a real-timing matrix and then a `TSEG=0` sweep in the same build
  directory executes the sweep against a binary built for a different bit
  time, producing false timeouts on long frames. Every timing configuration
  must use its own `SIM_BUILD`.
* **Shared model state / stale bytecode.** The mutation harness rewrites
  `tb/can_fd_reference.py` in place. CPython validates a cached `.pyc` by
  (mtime in seconds, size). A mutation that preserves file size, restored
  within the same second, leaves a cache that still passes validation, so
  later imports silently execute mutant bytecode. This produced false gate
  verdicts on unchanged source: 667 and later 2515 mismatches in the waveform
  gate, both summing with the matched count to 4999, the clean total. Proven
  on this machine: pyc mtime equal to disk mtime, cache marked VALID.
  Fixed by purging `__pycache__` / `.pytest_cache` at suite start and, in the
  harness `finally` block, resetting mtime, purging caches and byte-comparing
  the restored file against the pristine copy.

## 8. Reproduce

```bash
bash scripts/verify_all.sh
python3 scripts/make_docs.py
python3 scripts/make_report.py --lang both
```
"""

    return f"""# Методология верификации и доказательная база

Сгенерировано `scripts/make_docs.py` из `logs/` и `coverage/`.
Ревизия: `{m["git"]}` · Дата: {date.today().isoformat()}

Каждое число ниже разобрано из лога прогона. Если лог отсутствует, значение
показывается как `n/a`, а не подменяется правдоподобным.

## 1. Что измеряется

{gate_table(m, lang)}
## 2. Состав корпуса

| Формат | Векторов |
|---|---|
{corpus_lines}| **Всего** | **{c["total"]}** |
| в том числе синтетических | {c["synthetic"]} |

Векторы извлечены из открытого эталонного набора CTU CAN FD
(`reference_data_set_*.vhd` в `test/main_tb/`). Это эталонные наборы для
симуляции, а не захваты с кремния. Синтетические кадры помечены
`synthetic: true` и добавлены для закрытия пробела в мутационном покрытии
CRC-21; они используются мутационным стендом модели, а не RTL-прогоном
корпуса. Поэтому итог корпуса и итог RTL-прогона различаются.

## 3. Правила сравнения

* **Слот ACK исключён.** Приёмник драйвит его доминантным, модель передатчика
  выдаёт рецессивный. Расхождение в этой единственной позиции ожидаемо и не
  считается ошибкой.
* **Префикс обязан совпадать побитово.** Все биты до CRC-делителя включительно.
* **Хвост обязан быть рецессивным.** ACK-делитель, EOF, idle-паддинг.
* **Вне области:** remote-кадры (`rtr=1`), инъекции ошибок (`erf=1`),
  error-state кадры (`esi=1`).

## 4. Мутационное тестирование

Дефекты вносятся в эталонную модель. Мутант обязан быть обнаружен стендом
сравнения; выживший означает, что корпус не ограничивает это поведение.

| Мутант | Результат | Внесённый дефект |
|---|---|---|
{mut_lines}
## 5. Реальный двухфазный тайминг

`can_bit_timing` выдаёт `sample_en` на такте `TSEG1` и `bit_boundary` на
последнем такте `SYNC(1) + TSEG1 + TSEG2`. Фронт `brs_active` перепривязывает
`clk_cnt` и `tseg_cnt`, поэтому новая фаза всегда начинает бит с начала.

Приёмник переключает фазу в две стадии: значение BRS защёлкивается в точке
выборки, затем фаза коммитится на границе бита, завершающей номинальный бит
BRS — то же событие, что использует передатчик. Чтение защёлки в такте
выборки не работает: она пишется неблокирующим присваиванием в том же такте.

Покрыто `tests/test_bit_timing.py`, `tests/test_timing_phase_switch.py` и
`tests/test_timing_matrix.py` (DLC 0/4/8/12/15 × BRS вкл/выкл × паттерны
0x00 / 0xFF / чередующийся, для FBFF и FEFF).

## 6. Границы доказанного

* **{m["xval_deferred"]} векторов FD BRS=1 отложены** в кросс-чеке
  осциллограмм: он сэмплирует с фиксированной частотой и не может проследить
  смену скорости внутри кадра. Эти кадры покрыты матрицей реального тайминга.
* **Prescaler > 1 с очень короткой data-фазой** (`NBT_PRESCALER=2`, DBT=3
  такта) валит матрицу. Воспроизведено на базлайне до правок, то есть это
  существовавшее ограничение ресинхронизации, а не регрессия.
* **Fault confinement не реализован.** TEC/REC, error frames, bus-off.
* **Только симуляция.** Нет FPGA-сборки, нет кремния, нет квалификации
  ISO 26262.

## 7. Найденные ловушки окружения

* **Переиспользование старой сборки.** Каталог сборки кодирует параметры
  тайминга. Прогон матрицы реального тайминга, а затем свипа `TSEG=0` в том же
  каталоге исполняет свип на бинарнике с другой длиной бита и даёт ложные
  таймауты на длинных кадрах. Каждая конфигурация тайминга обязана иметь свой
  `SIM_BUILD`.
* **Разделяемое состояние модели / устаревший байткод.** Мутационный стенд
  перезаписывает `tb/can_fd_reference.py` на месте. CPython валидирует
  кэшированный `.pyc` по паре (mtime в секундах, размер). Мутация, сохраняющая
  размер файла, восстановленная в ту же секунду, оставляет кэш формально
  валидным, и последующие импорты молча исполняют мутантский байткод. Это
  давало ложные вердикты гейтов на неизменном коде: 667, а позже 2515
  расхождений в гейте осциллограмм — обе суммы с числом совпавших дают 4999,
  то есть чистый итог. Подтверждено на машине: mtime pyc равен mtime диска,
  кэш помечен VALID. Исправлено очисткой `__pycache__` / `.pytest_cache` на
  старте прогона и, в блоке `finally` стенда, сбросом mtime, очисткой кэшей и
  побайтовым сравнением восстановленного файла с эталонной копией.

## 8. Воспроизведение

```bash
bash scripts/verify_all.sh
python3 scripts/make_docs.py
python3 scripts/make_report.py --lang both
```
"""


def main():
    m = metrics()
    OUT.mkdir(exist_ok=True)
    for lang, name in (("en", "VERIFICATION.md"), ("ru", "VERIFICATION.ru.md")):
        p = OUT / name
        p.write_text(build(m, lang), encoding="utf-8")
        print(f"{p.relative_to(ROOT)}  ({len(mutants())} mutants)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
